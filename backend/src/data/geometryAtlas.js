function listGeometryAtlas(grade) {
  const g = Number(grade);
  const showAll = !Number.isFinite(g) || g >= 8;
  const items = showAll ? ATLAS.slice() : ATLAS.filter(entry => entry.fromGrade <= g);
  return {
    title: 'Atlas de figuri geometrice',
    intro: 'Toate figurile din programa de gimnaziu: plane și în spațiu. La fiecare ai desenul, formulele și ce trebuie să reții. Corpurile 3D se învârt — trage-le cu degetul sau cu mouse-ul.',
    plane: items.filter(entry => entry.kind === 'plane'),
    space: items.filter(entry => entry.kind === 'space'),
    all: items
  };
}

function figureIds() {
  return ATLAS.map(entry => entry.id);
}

module.exports = { ATLAS, listGeometryAtlas, figureIds };
