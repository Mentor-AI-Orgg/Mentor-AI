function extraTests() {
  if (SPECS.length !== 120) throw new Error(`completarea de română are ${SPECS.length} rânduri`);
  const grouped = new Map();
  SPECS.forEach(row => {
    const [key, id, lesson, level, skill, point, mode, prompt, answer, explain, steps] = row;
    const built = mode === 'n'
      ? counts([{ id, lesson, level, skill, point, prompt, explain, steps, proof: () => answer }])
      : words([{ id, lesson, level, skill, point, prompt, answer, explain, steps }]);
    if (!grouped.has(key)) grouped.set(key, []);
    grouped.get(key).push(built[0]);
  });
  return grouped;
}

